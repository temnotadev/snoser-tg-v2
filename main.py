class AsyncComplaintSender:
    def __init__(self, proxy_list, max_concurrent=15):
        self.proxies = proxy_list
        self.semaphore = asyncio.Semaphore(max_concurrent)
        self.ua = UserAgent()
        self.retries = 3
        self.timeout = aiohttp.ClientTimeout(total=20)

    async def _send_single(self, session, payload, proxy, retry_count=0):
        headers = {
            "User-Agent": self.ua.random,
            "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,image/webp,*/*;q=0.8",
            "Accept-Language": "ru-RU,ru;q=0.9,en-US;q=0.8,en;q=0.7",
            "Accept-Encoding": "gzip, deflate, br",
            "Connection": "keep-alive",
            "Upgrade-Insecure-Requests": "1",
            "Sec-Fetch-Dest": "document",
            "Sec-Fetch-Mode": "navigate",
            "Sec-Fetch-Site": "none",
            "Cache-Control": "max-age=0",
            "Referer": "https://telegram.org/",
            "Origin": "https://telegram.org"
        }
        
        try:
            async with session.post(
                "https://telegram.org/support",
                data=payload,
                headers=headers,
                proxy=proxy,
                timeout=self.timeout,
                ssl=ssl.create_default_context(cafile="cacert.pem")
            ) as resp:
                if resp.status in (200, 302):
                    return True, resp.status
                elif resp.status == 403 and retry_count < self.retries:
                    await asyncio.sleep(2 ** retry_count)
                    return await self._send_single(session, payload, proxy, retry_count + 1)
                elif resp.status == 429 and retry_count < self.retries:
                    await asyncio.sleep(5 * (retry_count + 1))
                    return await self._send_single(session, payload, proxy, retry_count + 1)
                return False, resp.status
        except Exception as e:
            if retry_count < self.retries:
                await asyncio.sleep(1)
                return await self._send_single(session, payload, proxy, retry_count + 1)
            return False, str(e)

    async def send_complaints(self, username, telegram_id, number, email, repeats, complaint_choice):
        text = self._build_text(username, telegram_id, complaint_choice)
        payload = {'text': text, 'number': number, 'email': email}
        success_count = 0
        
        async with aiohttp.ClientSession(timeout=self.timeout) as session:
            tasks = []
            for _ in range(int(repeats)):
                proxy = random.choice(self.proxies) if self.proxies else None
                task = asyncio.create_task(
                    self._send_single(session, payload, proxy)
                )
                tasks.append(task)
                if len(tasks) >= self.semaphore._value:
                    done, pending = await asyncio.wait(tasks, return_when=asyncio.FIRST_COMPLETED)
                    for d in done:
                        result, status = d.result()
                        if result:
                            success_count += 1
                    tasks = list(pending)
            
            if tasks:
                results = await asyncio.gather(*tasks, return_exceptions=True)
                for r in results:
                    if isinstance(r, tuple) and r[0]:
                        success_count += 1
        
        return success_count

